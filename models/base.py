"""Базовый класс сущностей предметной области."""


class Entity:
    """Сущность с идентификатором, которую можно сохранить в JSON.

    От этого класса наследуются Location, Film и Shooting:
    каждая из них «является» сохраняемой сущностью с полем id.
    Метод to_data() переопределяется в наследниках (полиморфизм),
    поэтому storage.py сохраняет любые сущности одной функцией.
    """

    def __init__(self, entity_id: int) -> None:
        """Сохранить идентификатор сущности."""
        self.id = entity_id

    def to_data(self) -> dict:
        """Вернуть данные сущности для записи в JSON."""
        raise NotImplementedError

    def __repr__(self) -> str:
        """Вернуть отладочное представление сущности."""
        return f"<{type(self).__name__} id={self.id}>"
